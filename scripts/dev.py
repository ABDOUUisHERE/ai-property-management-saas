ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
PORT_KEYS = ("DATABASE_PORT", "AUTH_PORT", "REDIS_PORT", "MAILPIT_HTTP_PORT", "S3_PORT")
SECRET_KEYS = (
    "DATABASE_ADMIN_PASSWORD",
    "DATABASE_MIGRATION_PASSWORD",
    "DATABASE_RUNTIME_PASSWORD",
    "DATABASE_DISPATCH_PASSWORD",
    "AUTH_DATABASE_ADMIN_PASSWORD",
    "AUTH_DATABASE_PASSWORD",
    "AUTH_JWT_SECRET",
    "REDIS_PASSWORD",
    "S3_ACCESS_KEY",
    "S3_SECRET_KEY",
)


def signing_key() -> dict[str, object]:
    """Return one ES256 signing JWK, accepted by GoTrue's key configuration."""
    private = ec.generate_private_key(ec.SECP256R1()).private_numbers()

    def encode(number: int) -> str:
        return base64.urlsafe_b64encode(number.to_bytes(32, "big")).rstrip(b"=").decode()

    return {
        "kty": "EC",
        "crv": "P-256",
        "alg": "ES256",
        "use": "sig",
        "key_ops": ["sign", "verify"],
        "kid": str(uuid.uuid4()),
        "x": encode(private.public_numbers.x),
        "y": encode(private.public_numbers.y),
        "d": encode(private.private_value),
    }


def read_env(path: Path) -> dict[str, str]:
    """Read the deliberately small, literal dotenv format generated by init."""
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or not re.fullmatch(r"[A-Z][A-Z0-9_]*", key) or key in values:
            raise ValueError("Invalid or duplicate dotenv key; values have been withheld")
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1]
        values[key] = value
    return values


def validate_env(values: dict[str, str]) -> None:
    """Reject remote targets and incomplete credentials before any smoke mutation."""
    required = set(read_env(ROOT / ".env.example"))
    if not required <= values.keys():
        raise ValueError("Local configuration is incomplete; run init")
    if values["APP_ENV"] != "local":
        raise ValueError("Infrastructure tooling accepts APP_ENV=local only")
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", values["COMPOSE_PROJECT_NAME"]):
        raise ValueError("Invalid Compose project name")
    ports = [int(values[key]) for key in PORT_KEYS]
    if len(set(ports)) != len(ports) or any(not 1024 <= port <= 65535 for port in ports):
        raise ValueError("Local ports must be distinct and between 1024 and 65535")
    if values["AUTH_EXTERNAL_URL"] != f"http://127.0.0.1:{values['AUTH_PORT']}":
        raise ValueError("Auth URL must match the local Auth port")
    site = urlparse(values["APP_SITE_URL"])
    if (
        site.scheme != "http"
        or site.hostname not in {"127.0.0.1", "localhost"}
        or site.username
        or site.password
        or site.query
        or site.fragment
        or site.path not in {"", "/"}
    ):
        raise ValueError("APP_SITE_URL must be a loopback HTTP origin")
    for key in SECRET_KEYS:
        if not re.fullmatch(r"[a-f0-9]{48,64}", values[key]):
            raise ValueError(f"{key} requires a generated local credential")
    if len({values[key] for key in SECRET_KEYS}) != len(SECRET_KEYS):
        raise ValueError("Local service credentials must be distinct")
    if not re.fullmatch(r"[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]", values["S3_BUCKET"]):
        raise ValueError("Invalid local S3 bucket name")
    keys = json.loads(values["AUTH_JWT_KEYS"])
    if len(keys) != 1 or keys[0].get("alg") != "ES256" or "d" not in keys[0]:
        raise ValueError("Auth requires one generated private ES256 signing key")
    jwt.PyJWK.from_dict(keys[0])


def init_environment(root: Path = ROOT, env_file: Path | None = None) -> bool:
    path = env_file or root / ".env"
    if path.exists():
        values = read_env(path)
        # P02 adds a separate capability for routing durable jobs. Preserve every
        # existing credential; append only the new key after validating the result.
        if "DATABASE_DISPATCH_PASSWORD" not in values:
            lock = path.with_name(path.name + ".upgrade.lock")
            descriptor = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            os.close(descriptor)
            try:
                values = read_env(path)
                if "DATABASE_DISPATCH_PASSWORD" not in values:
                    values["DATABASE_DISPATCH_PASSWORD"] = secrets.token_hex(24)
                    validate_env(values)
                    with path.open("a", encoding="utf-8", newline="\n") as stream:
                        stream.write(
                            f"\nDATABASE_DISPATCH_PASSWORD='{values['DATABASE_DISPATCH_PASSWORD']}'\n"
                        )
            finally:
                lock.unlink()
        validate_env(values)
        return False
    values = read_env(root / ".env.example")
    values.update({key: secrets.token_hex(24) for key in SECRET_KEYS})
    values["AUTH_JWT_KEYS"] = json.dumps([signing_key()], separators=(",", ":"))
    validate_env(values)
    content = "# Generated for local development only. Never commit this file.\n"
    content += "\n".join(f"{key}='{value}'" for key, value in values.items()) + "\n"
    # O_EXCL prevents a concurrent init from replacing already provisioned credentials.
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(content)
    return True


def compose(*arguments: str, capture: bool = True, env_file: Path = ROOT / ".env") -> str:
    executable = shutil.which("docker")
    if not executable:
        raise RuntimeError("Docker CLI is missing")
    values = read_env(env_file)
    validate_env(values)
    result = subprocess.run(  # noqa: S603 - fixed executable and argument list, no shell
        [
            executable,
            "compose",
            "--progress",
            "quiet",
            "--file",
            str(ROOT / "compose.yaml"),
            "--env-file",
            str(env_file.resolve()),
            "--project-name",
            values["COMPOSE_PROJECT_NAME"],
            *arguments,
        ],
        cwd=ROOT,
        env={**os.environ, **values},
        capture_output=capture,
        text=True,
        timeout=600,
        check=False,
    )
    if result.returncode:
        raise RuntimeError("Docker Compose failed; inspect service health without exposing .env")
    return result.stdout if capture else ""


def doctor(env_file: Path = ROOT / ".env") -> dict[str, str]:
    values = read_env(env_file)
    validate_env(values)
    executable = shutil.which("docker")
    if not executable:
        raise RuntimeError("Install Docker Desktop with the Linux engine")
    result = subprocess.run(  # noqa: S603
        [executable, "info", "--format", "{{.ServerVersion}}"],
        capture_output=True,
        text=True,
        timeout=20,
        check=False,
    )
    if result.returncode:
        raise RuntimeError("Docker engine is unavailable; start or resume Docker Desktop")
    compose("config", "--quiet", env_file=env_file)
    print("Local configuration and Docker engine: OK")
    return values


def expect(response: httpx.Response, codes: tuple[int, ...], stage: str) -> None:
    if response.status_code not in codes:
        # Request URLs and response bodies can contain tokens. Never include them in errors.
        raise RuntimeError(f"{stage}: unexpected HTTP status {response.status_code}")


def verify_token(token: str, jwks: dict, issuer: str) -> dict:
    header = jwt.get_unverified_header(token)
    if header.get("alg") != "ES256":
        raise RuntimeError("Auth did not use the expected ES256 signing algorithm")
    candidates = [key for key in jwks["keys"] if key["kid"] == header.get("kid")]
    if len(candidates) != 1 or "d" in candidates[0] or candidates[0].get("kty") != "EC":
        raise RuntimeError("Auth JWKS is missing its public key or exposes private material")
    return jwt.decode(
        token,
        jwt.PyJWK.from_dict(candidates[0]).key,
        algorithms=["ES256"],
        issuer=issuer,
        audience="authenticated",
        leeway=5,
        options={"require": ["exp", "iat", "iss", "aud", "sub"]},
    )


def confirmation_link(client: httpx.Client, mail_url: str, email: str, auth_url: str) -> str:
    deadline = time.monotonic() + 20
    while time.monotonic() < deadline:
        response = client.get(f"{mail_url}/api/v1/search", params={"query": f"to:{email}"})
        expect(response, (200,), "Mail search")
        messages = response.json().get("messages", [])
        for message in messages:
            response = client.get(f"{mail_url}/api/v1/message/{message['ID']}")
            expect(response, (200,), "Mail read")
            body = response.json()
            text = html.unescape(body.get("Text", "") + body.get("HTML", ""))
            for link in re.findall(r"https?://[^\s<>\"']+", text):
                parsed = urlparse(link)
                if f"{parsed.scheme}://{parsed.netloc}" == auth_url and parsed.path == "/verify":
                    return link
        time.sleep(0.5)
    raise RuntimeError("Confirmation email was not received in local Mailpit")


def smoke_auth(values: dict[str, str]) -> None:
    url = values["AUTH_EXTERNAL_URL"]
    mail_url = f"http://127.0.0.1:{values['MAILPIT_HTTP_PORT']}"
    email = f"infra-{uuid.uuid4().hex}@example.test"
    password = secrets.token_urlsafe(32)
    user_id = None
    key = json.loads(values["AUTH_JWT_KEYS"])[0]
    now = int(time.time())
    admin = jwt.encode(
        {"role": "service_role", "aud": "authenticated", "iss": url, "iat": now, "exp": now + 120},
        jwt.PyJWK.from_dict(key).key,
        algorithm="ES256",
        headers={"kid": key["kid"]},
    )
    with httpx.Client(timeout=10, follow_redirects=False, trust_env=False) as client:
        try:
            response = client.get(f"{url}/health")
            expect(response, (200,), "Auth health")
            response = client.post(f"{url}/signup", json={"email": email, "password": password})
            expect(response, (200,), "Auth signup")
            body = response.json()
            user_id = body.get("id") or body.get("user", {}).get("id")
            if not user_id:
                raise RuntimeError("Signup did not return the disposable fixture user")
            link = confirmation_link(client, mail_url, email, url)
            response = client.get(link)
            expect(
                response,
                (
                    302,
                    303,
                ),
                "Auth email confirmation",
            )
            response = client.post(
                f"{url}/token",
                params={"grant_type": "password"},
                json={"email": email, "password": password},
            )
            expect(response, (200,), "Auth login")
            tokens = response.json()
            response = client.get(f"{url}/.well-known/jwks.json")
            expect(response, (200,), "Auth JWKS")
            jwks = response.json()
            claims = verify_token(tokens["access_token"], jwks, url)
            if claims["sub"] != user_id:
                raise RuntimeError("Auth subject mismatch")
            response = client.post(
                f"{url}/token",
                params={"grant_type": "refresh_token"},
                json={"refresh_token": tokens["refresh_token"]},
            )
            expect(response, (200,), "Auth refresh")
            refreshed = response.json()
            verify_token(refreshed["access_token"], jwks, url)
            response = client.post(
                f"{url}/logout",
                headers={"Authorization": f"Bearer {refreshed['access_token']}"},
            )
            expect(response, (204,), "Auth logout")
            response = client.post(
                f"{url}/token",
                params={"grant_type": "refresh_token"},
                json={"refresh_token": refreshed["refresh_token"]},
            )
            expect(response, (400, 401, 403), "Revoked refresh token")
        finally:
            if user_id:
                response = client.delete(
                    f"{url}/admin/users/{uuid.UUID(user_id)}",
                    headers={"Authorization": f"Bearer {admin}"},
                )
                expect(response, (200, 204), "Disposable Auth fixture cleanup")
    print("Auth: signup, local email, confirmation, ES256/JWKS, login, refresh and logout OK")


def smoke_database(values: dict[str, str]) -> None:
    for role, password_key in (
        ("pms_app", "DATABASE_RUNTIME_PASSWORD"),
        ("pms_migrator", "DATABASE_MIGRATION_PASSWORD"),
    ):
        with psycopg.connect(
            host="127.0.0.1",
            port=int(values["DATABASE_PORT"]),
            dbname="property_management",
            user=role,
            password=values[password_key],
            connect_timeout=5,
        ) as connection:
            row = connection.execute(
                "SELECT rolsuper, rolbypassrls, rolcreatedb, rolcreaterole "
                "FROM pg_roles WHERE rolname = current_user"
            ).fetchone()
            if row != (False, False, False, False):
                raise RuntimeError("Database role has unexpected administrative privileges")
            if role == "pms_app":
                can_create = connection.execute(
                    "SELECT has_schema_privilege(current_user, 'public', 'CREATE')"
                ).fetchone()
                if can_create != (False,):
                    raise RuntimeError(
                        "Runtime role unexpectedly owns or can create schema objects"
                    )
    print("PostgreSQL: migration/runtime connections and restricted role privileges OK")


def smoke_storage(values: dict[str, str]) -> None:
    endpoint = f"http://127.0.0.1:{values['S3_PORT']}"
    bucket = values["S3_BUCKET"]
    key = f"infra-smoke/{uuid.uuid4().hex}.txt"
    payload = b"Fictitious infrastructure probe, no business data."
    storage = boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=values["S3_ACCESS_KEY"],
        aws_secret_access_key=values["S3_SECRET_KEY"],
        region_name="us-east-1",
        config=Config(
            signature_version="s3v4",
            s3={"addressing_style": "path"},
            connect_timeout=5,
            read_timeout=10,
            retries={"max_attempts": 2},
        ),
    )
    try:
        storage.head_bucket(Bucket=bucket)
    except ClientError as error:
        if error.response["ResponseMetadata"]["HTTPStatusCode"] != 404:
            raise
        storage.create_bucket(Bucket=bucket)
    try:
        storage.put_object(Bucket=bucket, Key=key, Body=payload)
        signed = storage.generate_presigned_url(
            "get_object",
            Params={"Bucket": bucket, "Key": key},
            ExpiresIn=60,
        )
        with httpx.Client(timeout=10, trust_env=False) as client:
            response = client.get(signed)
            expect(response, (200,), "Signed object read")
            if response.content != payload:
                raise RuntimeError("Object storage content mismatch")
            response = client.get(f"{endpoint}/{bucket}/{key}")
            expect(response, (401, 403), "Anonymous object read must be denied")
    finally:
        storage.delete_object(Bucket=bucket, Key=key)
    print("S3: private bucket, write, signed read, anonymous denial and fixture cleanup OK")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("init", "doctor", "up", "smoke", "status", "stop"))
    parser.add_argument("--env-file", type=Path, default=ROOT / ".env")
    args = parser.parse_args()
    if args.command == "init":
        created = init_environment(env_file=args.env_file)
        print(
            "Local .env generated; credentials withheld" if created else "Existing .env preserved"
        )
        return
    values = doctor(args.env_file)
    if args.command == "up":
        # Existing P01 volumes need the routing-only role; new volumes receive it
        # from init. Preserve the databases and all existing credentials.
        compose("up", "--wait", "--wait-timeout", "60", "postgres", env_file=args.env_file)
        from scripts.application import provision_dispatcher

        provision_dispatcher(args.env_file)
        compose(
            "up",
            "--build",
            "--wait",
            "--wait-timeout",
            "180",
            capture=False,
            env_file=args.env_file,
        )
    elif args.command == "smoke":
        smoke_database(values)
        if (
            compose("exec", "-T", "redis", "redis-cli", "ping", env_file=args.env_file).strip()
            != "PONG"
        ):
            raise RuntimeError("Redis did not answer the authenticated probe")
        print("Redis: authenticated PING OK")
        smoke_storage(values)
        smoke_auth(values)
    elif args.command == "status":
        print(compose("ps", env_file=args.env_file))
    elif args.command == "stop":
        compose("stop", capture=False, env_file=args.env_file)


if __name__ == "__main__":
    try:
        main()
    except (Exception, KeyboardInterrupt) as error:
        # Provider/driver exception strings can include credential-bearing URLs or payloads.
        if isinstance(error, (RuntimeError, ValueError, FileNotFoundError)):
            message = str(error) if isinstance(error, RuntimeError) else type(error).__name__
        else:
            message = type(error).__name__
        print(f"Local tooling failed: {message}", file=sys.stderr)
        sys.exit(1)
